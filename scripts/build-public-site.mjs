import {mkdir,readFile,writeFile,copyFile,rm} from 'node:fs/promises';
import {stickerPriceList} from '../local/sticker-prices.mjs';
import {initialState,productsFromTextilePriceList,validateState} from '../local/core.mjs';
const out=new URL('../dist/',import.meta.url);
await rm(out,{recursive:true,force:true});await mkdir(out,{recursive:true});
const textiles=JSON.parse(await readFile(new URL('../local/textile-prices.json',import.meta.url),'utf8'));
const state=initialState();state.products=productsFromTextilePriceList(textiles);state.textilePriceList=textiles;state.stickerPriceList=structuredClone(stickerPriceList);validateState(state);
await Promise.all(['index.html','app.js','style.css'].map(file=>copyFile(new URL(`../public/${file}`,import.meta.url),new URL(file,out))));
await copyFile(new URL('../local/core.mjs',import.meta.url),new URL('core.mjs',out));
await writeFile(new URL('initial-state.json',out),JSON.stringify(state,null,2));
console.log(`Komplette Browser-App erstellt: ${state.products.length} Produkte, ${state.stickerPriceList.formats.length} Aufkleberformate. Private Eingaben bleiben im localStorage.`);
